-- Etappe G, Teil 1: Shoot-Listen (eigene Listen mit Spots), Teilen per Token.

create table if not exists public.shoot_lists (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references public.profiles on delete cascade,
  name text not null check (char_length(name) between 1 and 40),
  share_token uuid not null default gen_random_uuid() unique,
  created_at timestamptz not null default now()
);
create index if not exists shoot_lists_owner_idx on public.shoot_lists (owner_id);

create table if not exists public.shoot_list_spots (
  list_id bigint not null references public.shoot_lists on delete cascade,
  spot_id bigint not null references public.spots on delete cascade,
  added_at timestamptz not null default now(),
  primary key (list_id, spot_id)
);

alter table public.shoot_lists enable row level security;
alter table public.shoot_list_spots enable row level security;
revoke all on public.shoot_lists, public.shoot_list_spots from anon, authenticated;
grant select, insert, delete on public.shoot_lists to authenticated;
grant update (name) on public.shoot_lists to authenticated;
grant select, insert, delete on public.shoot_list_spots to authenticated;

drop policy if exists "Eigene Listen" on public.shoot_lists;
create policy "Eigene Listen" on public.shoot_lists for all to authenticated
  using (owner_id = auth.uid()) with check (owner_id = auth.uid());

drop policy if exists "Spots in eigenen Listen" on public.shoot_list_spots;
create policy "Spots in eigenen Listen" on public.shoot_list_spots for all to authenticated
  using (exists (select 1 from public.shoot_lists l where l.id = list_id and l.owner_id = auth.uid()))
  with check (exists (select 1 from public.shoot_lists l where l.id = list_id and l.owner_id = auth.uid()));

-- Geteilte Liste lesen: nur mit dem Token, nur sichtbare Spots, ohne Besitzer-ID.
create or replace function public.shared_list(token uuid)
returns table (list_name text, owner_name text, spot_id bigint)
language sql stable security definer set search_path = public as $$
  select l.name, p.username, s.id
    from public.shoot_lists l
    left join public.profiles p on p.id = l.owner_id
    left join public.shoot_list_spots i on i.list_id = l.id
    left join public.spots s on s.id = i.spot_id and s.status = 'live'
   where l.share_token = token
   order by i.added_at;
$$;
revoke execute on function public.shared_list(uuid) from public, anon;
grant execute on function public.shared_list(uuid) to authenticated;
