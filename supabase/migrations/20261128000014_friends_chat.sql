-- Freunde und Chat (Testphase). Neue Tabellen, keine bestehenden Rechte gelockert, nichts für `anon`.
-- friendships: Anfrage (pending) → Annahme durch die andere Seite (accepted). messages: nur zwischen angenommenen Freunden.

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  requester uuid not null references public.profiles on delete cascade,
  addressee uuid not null references public.profiles on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'accepted')),
  created_at timestamptz not null default now(),
  check (requester <> addressee)
);
-- Ein Paar nur einmal, egal in welche Richtung.
create unique index if not exists friendships_pair_idx on public.friendships (least(requester, addressee), greatest(requester, addressee));
create index if not exists friendships_addressee_idx on public.friendships (addressee);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender uuid not null references public.profiles on delete cascade,
  recipient uuid not null references public.profiles on delete cascade,
  body text not null default '' check (char_length(body) <= 1000),
  spot_id bigint references public.spots on delete set null,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  check (sender <> recipient),
  check (char_length(btrim(body)) > 0 or spot_id is not null)
);
create index if not exists messages_pair_idx on public.messages (sender, recipient, created_at desc);
create index if not exists messages_unread_idx on public.messages (recipient) where read_at is null;

alter table public.friendships enable row level security;
alter table public.messages enable row level security;
revoke all on public.friendships, public.messages from anon, authenticated;
grant select, insert, delete on public.friendships to authenticated;
grant update (status) on public.friendships to authenticated;
grant select, insert on public.messages to authenticated;
grant update (read_at) on public.messages to authenticated;

drop policy if exists "Eigene Freundschaften lesen" on public.friendships;
create policy "Eigene Freundschaften lesen" on public.friendships for select to authenticated
  using (auth.uid() in (requester, addressee));
drop policy if exists "Anfrage senden" on public.friendships;
create policy "Anfrage senden" on public.friendships for insert to authenticated
  with check (requester = auth.uid() and status = 'pending');
-- Annehmen darf nur, wer angefragt wurde. Spalten ändern geht nur für `status` (Spalten-Recht).
drop policy if exists "Anfrage annehmen" on public.friendships;
create policy "Anfrage annehmen" on public.friendships for update to authenticated
  using (addressee = auth.uid() and status = 'pending') with check (addressee = auth.uid() and status = 'accepted');
drop policy if exists "Anfrage zurückziehen oder Freund entfernen" on public.friendships;
create policy "Anfrage zurückziehen oder Freund entfernen" on public.friendships for delete to authenticated
  using (auth.uid() in (requester, addressee));

drop policy if exists "Eigene Nachrichten lesen" on public.messages;
create policy "Eigene Nachrichten lesen" on public.messages for select to authenticated
  using (auth.uid() in (sender, recipient));
drop policy if exists "Nachricht an Freunde senden" on public.messages;
create policy "Nachricht an Freunde senden" on public.messages for insert to authenticated
  with check (sender = auth.uid() and exists (
    select 1 from public.friendships f
    where f.status = 'accepted'
      and ((f.requester = auth.uid() and f.addressee = recipient) or (f.addressee = auth.uid() and f.requester = recipient))));
-- Gelesen markieren nur der Empfänger (und nur die Spalte read_at).
drop policy if exists "Als gelesen markieren" on public.messages;
create policy "Als gelesen markieren" on public.messages for update to authenticated
  using (recipient = auth.uid()) with check (recipient = auth.uid());
