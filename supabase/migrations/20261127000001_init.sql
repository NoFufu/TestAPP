-- fitspot · Phase 1b · Grundschema
-- Spots, Fotos, Merkliste, Likes, Meldungen, Credits. Umkreissuche über PostGIS.

create extension if not exists postgis with schema extensions;

-- Profile (1:1 zu auth.users)
create table if not exists public.profiles (
  id uuid primary key references auth.users on delete cascade,
  username text unique,
  avatar_url text,
  credits integer not null default 0,
  created_at timestamptz not null default now()
);

create type public.spot_status as enum ('pending', 'live', 'rejected');
create type public.photo_kind as enum ('spot', 'outfit');

create table if not exists public.spots (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 60),
  description text not null default '',
  location extensions.geography(point, 4326) not null,
  area text not null default '',
  city text not null default 'Bielefeld',
  categories text[] not null check (cardinality(categories) between 1 and 4
    and categories <@ array['urban','tuer','natur','cafe','industrial','treppe','nacht','architektur']),
  status public.spot_status not null default 'pending',
  likes_count integer not null default 0,
  created_by uuid references public.profiles on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists spots_location_idx on public.spots using gist (location);
create index if not exists spots_status_idx on public.spots (status);

create table if not exists public.spot_photos (
  id bigint generated by default as identity primary key,
  spot_id bigint not null references public.spots on delete cascade,
  storage_path text not null,
  kind public.photo_kind not null default 'spot',
  status public.spot_status not null default 'pending',
  uploaded_by uuid references public.profiles on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists spot_photos_spot_idx on public.spot_photos (spot_id);

create table if not exists public.saves (
  user_id uuid not null references public.profiles on delete cascade,
  spot_id bigint not null references public.spots on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, spot_id)
);

create table if not exists public.likes (
  user_id uuid not null references public.profiles on delete cascade,
  photo_id bigint not null references public.spot_photos on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, photo_id)
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  photo_id bigint not null references public.spot_photos on delete cascade,
  reporter_id uuid references public.profiles on delete set null,
  reason text not null,
  status text not null default 'open' check (status in ('open', 'accepted', 'dismissed')),
  created_at timestamptz not null default now()
);

create table if not exists public.credit_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles on delete cascade,
  amount integer not null,
  reason text not null,
  ref_id bigint,
  created_at timestamptz not null default now()
);

-- Profil automatisch beim Registrieren anlegen
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id) values (new.id) on conflict do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Sicherheitsregeln (Row Level Security)
alter table public.profiles enable row level security;
alter table public.spots enable row level security;
alter table public.spot_photos enable row level security;
alter table public.saves enable row level security;
alter table public.likes enable row level security;
alter table public.reports enable row level security;
alter table public.credit_events enable row level security;

create policy "Profile sind lesbar" on public.profiles for select using (true);
create policy "Eigenes Profil ändern" on public.profiles for update using (auth.uid() = id);

create policy "Live-Spots lesen" on public.spots for select
  using (status = 'live' or created_by = auth.uid());
create policy "Spots einreichen" on public.spots for insert to authenticated
  with check (created_by = auth.uid() and status = 'pending');

create policy "Live-Fotos lesen" on public.spot_photos for select
  using (status = 'live' or uploaded_by = auth.uid());
create policy "Fotos einreichen" on public.spot_photos for insert to authenticated
  with check (uploaded_by = auth.uid() and status = 'pending');

create policy "Eigene Merkliste" on public.saves for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "Eigene Likes" on public.likes for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "Melden" on public.reports for insert to authenticated
  with check (reporter_id = auth.uid());
create policy "Eigene Credits sehen" on public.credit_events for select to authenticated
  using (user_id = auth.uid());

-- Umkreissuche: Live-Spots um einen Punkt, mit Entfernung und Titelbild
create or replace function public.spots_nearby(
  lat double precision, lon double precision,
  radius_m double precision default 15000,
  cats text[] default null
) returns table (
  id bigint, name text, description text, area text, categories text[],
  lat double precision, lon double precision, likes_count integer,
  dist_m double precision, cover_path text
)
language sql stable security invoker set search_path = public, extensions as $$
  select s.id, s.name, s.description, s.area, s.categories,
         st_y(s.location::geometry), st_x(s.location::geometry), s.likes_count,
         st_distance(s.location, st_makepoint(lon, lat)::geography) as dist_m,
         (select p.storage_path from public.spot_photos p
           where p.spot_id = s.id and p.status = 'live' and p.kind = 'spot'
           order by p.id limit 1)
  from public.spots s
  where s.status = 'live'
    and st_dwithin(s.location, st_makepoint(lon, lat)::geography, radius_m)
    and (cats is null or s.categories && cats)
  order by dist_m;
$$;

-- Bildspeicher: öffentlich lesbar, Hochladen nur eingeloggt in den eigenen Ordner
insert into storage.buckets (id, name, public) values ('spot-photos', 'spot-photos', true)
  on conflict (id) do nothing;
create policy "Fotos hochladen" on storage.objects for insert to authenticated
  with check (bucket_id = 'spot-photos' and (storage.foldername(name))[1] = auth.uid()::text);
