-- Testphase: Feedback aus der App und anonyme Nutzungs-Ereignisse für die Ziele (PRODUKT-PLAN Kap. 6).
-- Nur Einfügen für angemeldete Nutzer, Lesen nur für Admins (über admin_testphase_stats).

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles on delete set null,
  message text not null check (char_length(message) between 1 and 2000),
  app_version text,
  created_at timestamptz not null default now()
);

create table if not exists public.app_events (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles on delete cascade,
  event text not null check (event in ('app_open', 'spot_saved', 'route_opened', 'upload_done', 'list_shared')),
  created_at timestamptz not null default now()
);
create index if not exists app_events_event_idx on public.app_events (event, created_at);

alter table public.feedback enable row level security;
alter table public.app_events enable row level security;
revoke all on public.feedback, public.app_events from anon, authenticated;
grant insert on public.feedback, public.app_events to authenticated;

drop policy if exists "Feedback senden" on public.feedback;
create policy "Feedback senden" on public.feedback for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "Ereignis senden" on public.app_events;
create policy "Ereignis senden" on public.app_events for insert to authenticated with check (user_id = auth.uid());

-- Kennzahlen für Admins: Anteil der Tester je Ziel.
create or replace function public.admin_testphase_stats()
returns table (testers int, saved_pct int, route_pct int, upload_pct int, returned_pct int, feedback_count int)
language plpgsql stable security definer set search_path = public as $$
declare t int;
begin
  if not public.is_admin() then raise exception 'nur für Admins' using errcode = '42501'; end if;
  select count(distinct user_id) into t from public.app_events where event = 'app_open';
  return query select t,
    (100 * (select count(distinct user_id) from public.app_events where event = 'spot_saved') / greatest(t, 1))::int,
    (100 * (select count(distinct user_id) from public.app_events where event = 'route_opened') / greatest(t, 1))::int,
    (100 * (select count(distinct user_id) from public.app_events where event = 'upload_done') / greatest(t, 1))::int,
    (100 * (select count(*) from (select user_id from public.app_events where event = 'app_open'
       group by user_id having max(created_at) - min(created_at) >= interval '7 days') x) / greatest(t, 1))::int,
    (select count(*) from public.feedback)::int;
end $$;

create or replace function public.admin_feedback()
returns table (message text, username text, app_version text, created_at timestamptz)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'nur für Admins' using errcode = '42501'; end if;
  return query select f.message, p.username, f.app_version, f.created_at
    from public.feedback f left join public.profiles p on p.id = f.user_id order by f.created_at desc limit 200;
end $$;

revoke execute on function public.admin_testphase_stats(), public.admin_feedback() from public, anon;
grant execute on function public.admin_testphase_stats(), public.admin_feedback() to authenticated;
